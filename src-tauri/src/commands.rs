/// Fires the RFC 8058 one-click POST. Plain HTTPS request, no Gmail API/OAuth involved.
/// The frontend must have already gotten explicit user confirmation before calling this -
/// it is never invoked automatically during sync.
#[tauri::command]
pub async fn unsubscribe_via_post(state: State<'_, AppState>, email_id: i64) -> Result<(), String> {
    let info = unsubscribe_info_inner(&state, email_id)?;
    if info.unsubscribed_at.is_some() {
        return Ok(());
    }
    let url = match info.method {
        UnsubscribeMethod::OneClickPost { url } => url,
        _ => return Err("this email does not support one-click unsubscribe".to_string()),
    };
    unsubscribe::one_click_post(&url).await?;
    mark_unsubscribed(&state, email_id)
}

/// Opens the (non-one-click) unsubscribe URL in the system browser, same mechanism as the
/// OAuth login flow. Best-effort marks the email unsubscribed - the app can't observe
/// whether the user actually completed the webpage flow, so this is a deliberate
/// simplification: "opened" is treated as "handled".
#[tauri::command]
pub async fn unsubscribe_open_browser(app: AppHandle, state: State<'_, AppState>, email_id: i64) -> Result<(), String> {
    let info = unsubscribe_info_inner(&state, email_id)?;
    if info.unsubscribed_at.is_some() {
        return Ok(());
    }
    let url = match info.method {
        UnsubscribeMethod::Browser { url } => url,
        _ => return Err("this email has no browser unsubscribe link".to_string()),
    };
    app.shell()
        .open(url, None)
        .map_err(|e| format!("failed to open browser: {e}"))?;
    mark_unsubscribed(&state, email_id)
}

/// Sends a real email to unsubscribe, via `drafts.create` + `drafts.send` - the app's
/// one deliberate use of its incidental send capability (see `auth/oauth.rs`). Only
/// reachable when `classify()` found a mailto-only `List-Unsubscribe` target; the
/// frontend must show a confirmation explicitly stating an email will be sent.
#[tauri::command]
pub async fn unsubscribe_via_mailto(app: AppHandle, state: State<'_, AppState>, email_id: i64) -> Result<(), String> {
    let info = unsubscribe_info_inner(&state, email_id)?;
    if info.unsubscribed_at.is_some() {
        return Ok(());
    }
    let (to, subject, body) = match info.method {
        UnsubscribeMethod::Mailto { to, subject, body } => (to, subject, body),
        _ => return Err("this email has no mailto unsubscribe target".to_string()),
    };

    let account_id: i64 = {
        let conn = state.db.lock().map_err(|e| e.to_string())?;
        conn.query_row(
            "SELECT account_id FROM emails WHERE id = ?1",
            params![email_id],
            |row| row.get(0),
        )
        .map_err(|e| e.to_string())?
    };
    let account_email: String = {
        let conn = state.db.lock().map_err(|e| e.to_string())?;
        conn.query_row(
            "SELECT email_address FROM accounts WHERE id = ?1",
            params![account_id],
            |row| row.get(0),
        )
        .map_err(|e| e.to_string())?
    };

    let config = load_oauth_config(&app)?;
    let refresh_token = keyring_store::get_refresh_token(&account_email)
        .map_err(|e| format!("no stored refresh token: {e}"))?;
    let access_token = oauth::refresh_access_token(&config, &refresh_token).await?;
    let client = GmailClient::new(access_token);

    let draft_id = client
        .create_draft(
            &account_email,
            &to,
            None,
            subject.as_deref().unwrap_or("Unsubscribe"),
            body.as_deref().unwrap_or(""),
            None, // deliberately not threaded onto the original email
            None,
        )
        .await?;
    client.send_draft(&draft_id).await?; // only mark unsubscribed after a confirmed send

    mark_unsubscribed(&state, email_id)
}

