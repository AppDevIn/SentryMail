/// Creates a reply draft in Gmail and, when `send` is true, sends it at once (ADR 0010).
/// Refuses on DANGER-risk emails even if somehow called - the UI never shows
/// a reply control for those, but this is a deliberate defense in depth.
#[tauri::command]
pub async fn create_gmail_draft(
    app: AppHandle,
    state: State<'_, AppState>,
    email_id: i64,
    body_override: Option<String>,
    reply_all: Option<bool>,
    send: Option<bool>,
) -> Result<String, String> {
    let config = load_oauth_config(&app)?;

    let (account_id, sender, subject, gmail_thread_id, rfc_message_id, stored_draft, risk, to_addrs, cc_addrs): (
        i64,
        String,
        String,
        String,
        Option<String>,
        Option<String>,
        Option<String>,
        String,
        String,
    ) = {
        let conn = state.db.lock().map_err(|e| e.to_string())?;
        conn.query_row(
            "SELECT e.account_id, e.sender, e.subject, e.gmail_thread_id, e.rfc_message_id,
                    t.draft_reply, COALESCE(t.user_risk, t.risk), COALESCE(e.to_addrs, ''), COALESCE(e.cc_addrs, '')
             FROM emails e LEFT JOIN triage_results t ON t.email_id = e.id
             WHERE e.id = ?1",
            params![email_id],
            |row| {
                Ok((
                    row.get(0)?,
                    row.get(1)?,
                    row.get(2)?,
                    row.get(3)?,
                    row.get(4)?,
                    row.get(5)?,
                    row.get(6)?,
                    row.get(7)?,
                    row.get(8)?,
                ))
            },
        )
        .map_err(|e| e.to_string())?
    };

    if risk.as_deref() == Some("danger") {
        return Err("Refusing to save a draft for an email flagged as DANGER risk".to_string());
    }

    let body = body_override
        .or(stored_draft)
        .ok_or("No draft reply available for this email")?;

    let account_email: String = {
        let conn = state.db.lock().map_err(|e| e.to_string())?;
        conn.query_row(
            "SELECT email_address FROM accounts WHERE id = ?1",
            params![account_id],
            |row| row.get(0),
        )
        .map_err(|e| e.to_string())?
    };

    let refresh_token = keyring_store::get_refresh_token(&account_email)
        .map_err(|e| format!("no stored refresh token: {e}"))?;
    let access_token = oauth::refresh_access_token(&config, &refresh_token).await?;
    let client = GmailClient::new(access_token);

    let to = extract_email_address(&sender);
    // Reply all: everyone on the original To/Cc except the sender and the user.
    let cc = if reply_all.unwrap_or(false) {
        let mut seen = std::collections::HashSet::new();
        let me = account_email.to_ascii_lowercase();
        let others: Vec<String> = format!("{to_addrs},{cc_addrs}")
            .split(',')
            .map(|a| extract_email_address(a.trim()))
            .filter(|a| !a.is_empty() && a.contains('@'))
            .filter(|a| {
                let l = a.to_ascii_lowercase();
                l != me && l != to.to_ascii_lowercase() && seen.insert(l)
            })
            .collect();
        if others.is_empty() { None } else { Some(others.join(", ")) }
    } else {
        None
    };
    let reply_subject = if subject.to_lowercase().starts_with("re:") {
        subject.clone()
    } else {
        format!("Re: {subject}")
    };

    let draft_id = client
        .create_draft(
            &account_email,
            &to,
            cc.as_deref(),
            &reply_subject,
            &body,
            Some(&gmail_thread_id),
            rfc_message_id.as_deref(),
        )
        .await?;

    {
        let conn = state.db.lock().map_err(|e| e.to_string())?;
        conn.execute(
            "UPDATE triage_results SET gmail_draft_id = ?1 WHERE email_id = ?2",
            params![draft_id, email_id],
        )
        .map_err(|e| e.to_string())?;
    }
    if send.unwrap_or(false) {
        client.send_draft(&draft_id).await?;
    }

    Ok(draft_id)
}

