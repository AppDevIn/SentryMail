/// Archives (removes `INBOX` from) or restores every message of the thread `email_id`
/// belongs to: locally at once, then best effort on Gmail (ADR 0010).
#[derive(Debug, Serialize)]
pub struct ArchiveResult {
    pub archived: bool,
    pub warning: Option<String>,
}

#[tauri::command]
pub async fn archive_thread(
    app: AppHandle,
    state: State<'_, AppState>,
    email_id: i64,
    archived: bool,
) -> Result<ArchiveResult, String> {
    let (message_ids, account_email): (Vec<String>, String) = {
        let db = state.db.lock().map_err(|e| e.to_string())?;
        let (account_id, thread_id, account_email): (i64, String, String) = db
            .query_row(
                "SELECT e.account_id, e.gmail_thread_id, a.email_address
                 FROM emails e JOIN accounts a ON a.id = e.account_id WHERE e.id = ?1",
                params![email_id],
                |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?)),
            )
            .map_err(|e| e.to_string())?;
        let mut stmt = db
            .prepare("SELECT gmail_message_id FROM emails WHERE account_id = ?1 AND gmail_thread_id = ?2")
            .map_err(|e| e.to_string())?;
        let ids = stmt
            .query_map(params![account_id, thread_id], |row| row.get::<_, String>(0))
            .map_err(|e| e.to_string())?
            .collect::<Result<Vec<_>, _>>()
            .map_err(|e| e.to_string())?;
        let inbox = vec!["INBOX".to_string()];
        for mid in &ids {
            if archived {
                update_label_ids(&db, account_id, mid, &[], &inbox)?;
            } else {
                update_label_ids(&db, account_id, mid, &inbox, &[])?;
            }
        }
        (ids, account_email)
    };

    let gmail = async {
        let config = load_oauth_config(&app)?;
        let refresh_token = keyring_store::get_refresh_token(&account_email)
            .map_err(|e| format!("no stored refresh token: {e}"))?;
        let access_token = oauth::refresh_access_token(&config, &refresh_token).await?;
        let client = GmailClient::new(access_token);
        for id in &message_ids {
            if archived {
                client.modify_labels(id, &[], &["INBOX"]).await?;
            } else {
                client.modify_labels(id, &["INBOX"], &[]).await?;
            }
        }
        Ok::<(), String>(())
    };
    let warning = match gmail.await {
        Ok(()) => None,
        Err(e) => Some(format!(
            "{} here, but Gmail wasn't updated: {e}",
            if archived { "Archived" } else { "Moved to inbox" }
        )),
    };
    Ok(ArchiveResult { archived, warning })
}

/// Composes and sends a new message from `account_id` (ADR 0010). The draft is created
/// then sent through `drafts/send`, the same path the mailto unsubscribe uses.
#[tauri::command]
pub async fn send_message(
    app: AppHandle,
    state: State<'_, AppState>,
    account_id: i64,
    to: String,
    cc: Option<String>,
    subject: String,
    body: String,
) -> Result<(), String> {
    let to = to.trim().to_string();
    if to.is_empty() || !to.contains('@') {
        return Err("Add at least one recipient address".to_string());
    }
    if body.trim().is_empty() {
        return Err("The message is empty".to_string());
    }
    let account_email: String = {
        let conn = state.db.lock().map_err(|e| e.to_string())?;
        conn.query_row("SELECT email_address FROM accounts WHERE id = ?1", params![account_id], |row| row.get(0))
            .map_err(|e| e.to_string())?
    };
    let config = load_oauth_config(&app)?;
    let refresh_token = keyring_store::get_refresh_token(&account_email)
        .map_err(|e| format!("no stored refresh token: {e}"))?;
    let access_token = oauth::refresh_access_token(&config, &refresh_token).await?;
    let client = GmailClient::new(access_token);
    let cc = cc.map(|c| c.trim().to_string()).filter(|c| !c.is_empty());
    let subject = if subject.trim().is_empty() { "(no subject)".to_string() } else { subject.trim().to_string() };
    let draft_id = client
        .create_draft(&account_email, &to, cc.as_deref(), &subject, &body, None, None)
        .await?;
    client.send_draft(&draft_id).await
}

#[derive(Debug, Serialize)]
pub struct SetReadResult {
    pub synced_to_gmail: bool,
    pub warning: Option<String>,
}

/// Marks an email read/unread: locally at once (so the UI is instant and works offline),
/// then best-effort on Gmail. A token granted before the `gmail.modify` scope was added can't
/// update Gmail; that's reported as a warning, never as a failure.
#[tauri::command]
pub async fn set_read(
    app: AppHandle,
    state: State<'_, AppState>,
    email_id: i64,
    is_read: bool,
) -> Result<SetReadResult, String> {
    // Read state is per conversation (as in Gmail): every message in the thread flips.
    let (message_ids, account_email): (Vec<String>, String) = {
        let db = state.db.lock().map_err(|e| e.to_string())?;
        let (account_id, thread_id, account_email): (i64, String, String) = db
            .query_row(
                "SELECT e.account_id, e.gmail_thread_id, a.email_address
                 FROM emails e JOIN accounts a ON a.id = e.account_id WHERE e.id = ?1",
                params![email_id],
                |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?)),
            )
            .map_err(|e| e.to_string())?;
        let mut stmt = db
            .prepare(
                "SELECT gmail_message_id FROM emails
                 WHERE account_id = ?1 AND gmail_thread_id = ?2 AND is_read != ?3",
            )
            .map_err(|e| e.to_string())?;
        let ids = stmt
            .query_map(params![account_id, thread_id, is_read], |row| row.get::<_, String>(0))
            .map_err(|e| e.to_string())?
            .collect::<Result<Vec<_>, _>>()
            .map_err(|e| e.to_string())?;
        db.execute(
            "UPDATE emails SET is_read = ?1 WHERE account_id = ?2 AND gmail_thread_id = ?3",
            params![is_read, account_id, thread_id],
        )
        .map_err(|e| e.to_string())?;
        (ids, account_email)
    };
    if message_ids.is_empty() {
        return Ok(SetReadResult {
            synced_to_gmail: true,
            warning: None,
        });
    }

    let gmail = async {
        let config = load_oauth_config(&app)?;
        let refresh_token = keyring_store::get_refresh_token(&account_email)
            .map_err(|e| format!("no stored refresh token: {e}"))?;
        let access_token = oauth::refresh_access_token(&config, &refresh_token).await?;
        let client = GmailClient::new(access_token);
        for id in &message_ids {
            if is_read {
                client.modify_labels(id, &[], &["UNREAD"]).await?;
            } else {
                client.modify_labels(id, &["UNREAD"], &[]).await?;
            }
        }
        Ok::<(), String>(())
    };
    match gmail.await {
        Ok(()) => Ok(SetReadResult {
            synced_to_gmail: true,
            warning: None,
        }),
        Err(e) => Ok(SetReadResult {
            synced_to_gmail: false,
            warning: Some(if e.contains("insufficient permission") {
                format!(
                    "Marked {} here, but Gmail wasn't updated: {e}. Use Add inbox with {account_email} again to grant it.",
                    if is_read { "read" } else { "unread" }
                )
            } else {
                format!("Marked {} here, but Gmail wasn't updated: {e}", if is_read { "read" } else { "unread" })
            }),
        }),
    }
}

