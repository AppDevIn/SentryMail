/// Which of the user's *described* labels the local model thinks fit this email.
#[tauri::command]
pub async fn suggest_labels(state: State<'_, AppState>, email_id: i64) -> Result<Vec<LabelSuggestion>, String> {
    let (handle, user_email, described) = {
        let llm_slot = state.triage_llm.lock().map_err(|e| e.to_string())?;
        let handle = llm_slot.clone().ok_or("model not loaded - call load_model first")?;
        let db = state.db.lock().map_err(|e| e.to_string())?;
        let (account_id, user_email): (i64, String) = db
            .query_row(
                "SELECT e.account_id, a.email_address FROM emails e JOIN accounts a ON a.id = e.account_id WHERE e.id = ?1",
                params![email_id],
                |row| Ok((row.get(0)?, row.get(1)?)),
            )
            .map_err(|e| e.to_string())?;
        let mut stmt = db
            .prepare("SELECT gmail_label_id, name, description FROM labels WHERE account_id = ?1 AND label_type = 'user' AND description IS NOT NULL AND description != ''")
            .map_err(|e| e.to_string())?;
        let described = stmt
            .query_map(params![account_id], |row| Ok((row.get::<_, String>(0)?, row.get::<_, String>(1)?, row.get::<_, String>(2)?)))
            .map_err(|e| e.to_string())?
            .collect::<Result<Vec<_>, _>>()
            .map_err(|e| e.to_string())?;
        (handle, user_email, described)
    };
    if described.is_empty() {
        return Err("describe at least one label in the sidebar first, so the model knows what to look for".to_string());
    }
    let pairs: Vec<(String, String)> = described.iter().map(|(_, n, d)| (n.clone(), d.clone())).collect();
    let names = triage::suggest_labels(&state.db, &handle, email_id, &user_email, &pairs).await?;
    Ok(described
        .into_iter()
        .filter(|(_, n, _)| names.contains(n))
        .map(|(id, n, _)| LabelSuggestion { gmail_label_id: id, name: n })
        .collect())
}

#[derive(Debug, Serialize)]
pub struct ApplyLabelsResult {
    pub label_ids: Vec<String>,
    pub warning: Option<String>,
}

async fn apply_labels_inner(
    app: &AppHandle,
    state: &State<'_, AppState>,
    email_id: i64,
    add: &[String],
    remove: &[String],
) -> Result<ApplyLabelsResult, String> {
    {
        let db = state.db.lock().map_err(|e| e.to_string())?;
        let row: (i64, String) = db
            .query_row(
                "SELECT account_id, gmail_message_id FROM emails WHERE id = ?1",
                params![email_id],
                |row| Ok((row.get::<_, i64>(0)?, row.get::<_, String>(1)?)),
            )
            .map_err(|e| e.to_string())?;
        update_label_ids(&db, row.0, &row.1, add, remove)?;
    }
    let gmail = async {
        let (client, mid) = gmail_client_for_email(app, state, email_id).await?;
        let add_refs: Vec<&str> = add.iter().map(String::as_str).collect();
        let rm_refs: Vec<&str> = remove.iter().map(String::as_str).collect();
        client.modify_labels(&mid, &add_refs, &rm_refs).await.map(|_| mid)
    };
    let warning = match gmail.await {
        Ok(_) => None,
        Err(e) => Some(format!("Label saved here, but Gmail wasn't updated: {e}")),
    };
    let label_ids = {
        let db = state.db.lock().map_err(|e| e.to_string())?;
        parse_label_ids(
            db.query_row("SELECT label_ids FROM emails WHERE id = ?1", params![email_id], |row| row.get(0))
                .ok()
                .flatten(),
        )
    };
    Ok(ApplyLabelsResult { label_ids, warning })
}

/// Adds/removes Gmail labels on an email (locally at once, then on Gmail best effort).
#[tauri::command]
pub async fn apply_labels(
    app: AppHandle,
    state: State<'_, AppState>,
    email_id: i64,
    add: Vec<String>,
    remove: Vec<String>,
) -> Result<ApplyLabelsResult, String> {
    apply_labels_inner(&app, &state, email_id, &add, &remove).await
}

/// After analysis: apply any auto-apply labels the model thinks fit. Best effort, silent.
async fn auto_label(app: &AppHandle, state: &State<'_, AppState>, email_id: i64) {
    let auto: Vec<(String, String, String)> = {
        let Ok(db) = state.db.lock() else { return };
        let Ok(mut stmt) = db.prepare(
            "SELECT l.gmail_label_id, l.name, l.description FROM labels l
             JOIN emails e ON e.account_id = l.account_id
             WHERE e.id = ?1 AND l.label_type = 'user' AND l.auto_apply = 1
               AND l.description IS NOT NULL AND l.description != ''",
        ) else { return };
        let Ok(rows) = stmt.query_map(params![email_id], |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?))) else { return };
        rows.filter_map(Result::ok).collect()
    };
    if auto.is_empty() {
        return;
    }
    let Ok(suggestions) = suggest_labels(state.clone(), email_id).await else { return };
    let current: Vec<String> = {
        let Ok(db) = state.db.lock() else { return };
        parse_label_ids(db.query_row("SELECT label_ids FROM emails WHERE id = ?1", params![email_id], |row| row.get(0)).ok().flatten())
    };
    let add: Vec<String> = suggestions
        .into_iter()
        .filter(|s| auto.iter().any(|(id, _, _)| id == &s.gmail_label_id) && !current.contains(&s.gmail_label_id))
        .map(|s| s.gmail_label_id)
        .collect();
    if !add.is_empty() {
        let _ = apply_labels_inner(app, state, email_id, &add, &[]).await;
    }
}

/// Incremental sync from Gmail's history API: new inbox messages plus read/unread changes
/// made anywhere (phone, web). Returns None when the stored history id has expired.
async fn sync_incremental(
    app: &AppHandle,
    state: &State<'_, AppState>,
    client: &GmailClient,
    account_id: i64,
    email_address: &str,
    start_history_id: &str,
) -> Result<Option<u32>, String> {
    use crate::gmail::client::HistoryOutcome;
    let mut page_token: Option<String> = None;
    let mut new_count = 0;
    let mut seen = 0u32;
    loop {
        let outcome = client.list_history(start_history_id, page_token.as_deref()).await?;
        let (records, next) = match outcome {
            HistoryOutcome::Expired => return Ok(None),
            HistoryOutcome::Page { records, next_page_token } => (records, next_page_token),
        };
        for record in records {
            for added in record.messages_added {
                if added.message.label_ids.iter().any(|l| l == "INBOX")
                    && upsert_message(state, client, account_id, &added.message.id).await?
                {
                    new_count += 1;
                }
            }
            let db = state.db.lock().map_err(|e| e.to_string())?;
            for change in record.labels_added {
                if change.label_ids.iter().any(|l| l == "UNREAD") {
                    db.execute(
                        "UPDATE emails SET is_read = 0 WHERE account_id = ?1 AND gmail_message_id = ?2",
                        params![account_id, change.message.id],
                    )
                    .map_err(|e| e.to_string())?;
                }
                update_label_ids(&db, account_id, &change.message.id, &change.label_ids, &[])?;
            }
            for change in record.labels_removed {
                if change.label_ids.iter().any(|l| l == "UNREAD") {
                    db.execute(
                        "UPDATE emails SET is_read = 1 WHERE account_id = ?1 AND gmail_message_id = ?2",
                        params![account_id, change.message.id],
                    )
                    .map_err(|e| e.to_string())?;
                }
                update_label_ids(&db, account_id, &change.message.id, &[], &change.label_ids)?;
            }
            seen += 1;
        }
        emit_sync_progress(app, email_address, "history", seen, None);
        page_token = next;
        if page_token.is_none() {
            break;
        }
    }
    Ok(Some(new_count))
}

async fn sync_account(
    app: &AppHandle,
    state: &State<'_, AppState>,
    config: &oauth::OauthConfig,
    account_id: i64,
    email_address: &str,
) -> Result<u32, String> {
    let refresh_token = keyring_store::get_refresh_token(email_address)
        .map_err(|e| format!("no stored refresh token: {e}"))?;
    let access_token = oauth::refresh_access_token(config, &refresh_token).await?;
    let client = GmailClient::new(access_token);
    sync_labels(state, &client, account_id).await?;

    // Snapshot the mailbox history id *before* listing, so anything that arrives while we
    // sync is picked up by the next incremental run rather than lost in the gap.
    let history_now = client.current_history_id().await.ok();
    let last_history_id: Option<String> = {
        let db = state.db.lock().map_err(|e| e.to_string())?;
        db.query_row(
            "SELECT last_history_id FROM accounts WHERE id = ?1",
            params![account_id],
            |row| row.get::<_, Option<String>>(0),
        )
        .map_err(|e| e.to_string())?
    };

    let mut new_count: Option<u32> = None;
    if let Some(start) = last_history_id.as_deref() {
        new_count = sync_incremental(app, state, &client, account_id, email_address, start).await?;
    }
    let mut new_count = match new_count {
        Some(n) => n,
        None => sync_full(app, state, &client, account_id, email_address).await?,
    };
    // Keep walking back through older mail a batch at a time (no-op once complete).
    new_count += sync_backfill(app, state, &client, account_id, email_address).await?;

    if let Some(h) = history_now {
        let db = state.db.lock().map_err(|e| e.to_string())?;
        db.execute(
            "UPDATE accounts SET last_history_id = ?1, updated_at = datetime('now') WHERE id = ?2",
            params![h, account_id],
        )
        .map_err(|e| e.to_string())?;
    }
    emit_sync_progress(app, email_address, "done", new_count, None);
    Ok(new_count)
}

