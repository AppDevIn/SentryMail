/// Starts loading the model on a dedicated worker thread and returns
/// immediately; the frontend follows progress via the `triage-model-status` event.
#[tauri::command]
pub fn load_model(app: AppHandle, state: State<'_, AppState>) -> Result<(), String> {
    let mut llm_slot = state.triage_llm.lock().map_err(|e| e.to_string())?;
    if llm_slot.is_some() {
        return Ok(()); // already loading/loaded
    }
    let path = llm::triage_model_path(&app)?;
    if !path.exists() {
        return Err(format!(
            "No model file at {}. Download a Gemma GGUF model and place it there (see SETUP.md).",
            path.display()
        ));
    }
    let handle = llm::spawn_worker(app.clone(), path);
    *llm_slot = Some(handle);
    Ok(())
}

