#[tauri::command]
pub fn embedding_model_status(app: AppHandle, state: State<'_, AppState>) -> Result<ModelStatus, String> {
    let has_handle = state.embed_llm.lock().map_err(|e| e.to_string())?.is_some();
    if !has_handle {
        let path = llm::embedding_model_path(&app)?;
        return Ok(if path.exists() {
            ModelStatus::NotLoaded
        } else {
            ModelStatus::NotConfigured
        });
    }
    Ok(state.embed_model_status.lock().map_err(|e| e.to_string())?.clone())
}

/// Spawns the embedding worker (if not already running) and stores its handle. Shared by
/// the `load_embedding_model` command and the startup auto-load in `lib.rs` (ADR 0005).
/// The worker itself reports `embed-model-status` as it loads.
pub(crate) fn start_embed_worker(app: &AppHandle, state: &AppState) -> Result<(), String> {
    let mut embed_slot = state.embed_llm.lock().map_err(|e| e.to_string())?;
    if embed_slot.is_some() {
        return Ok(());
    }
    let path = llm::embedding_model_path(app)?;
    if !path.exists() {
        return Err(format!(
            "No embedding model file at {}. Download an EmbeddingGemma GGUF model and place it there (see SETUP.md).",
            path.display()
        ));
    }
    let handle = llm::spawn_embed_worker(app.clone(), path);
    *embed_slot = Some(handle);
    Ok(())
}

/// Mirrors `load_model`, for the embedding worker. Frontend follows progress via the
/// `embed-model-status` event.
#[tauri::command]
pub fn load_embedding_model(app: AppHandle, state: State<'_, AppState>) -> Result<(), String> {
    start_embed_worker(&app, state.inner())
}

async fn embed_one(state: &State<'_, AppState>, email_id: i64) -> Result<(), String> {
    let handle = {
        let slot = state.embed_llm.lock().map_err(|e| e.to_string())?;
        slot.clone()
            .ok_or("embedding model not loaded - call load_embedding_model first")?
    };
    search::embed_email(&state.db, &handle, email_id).await
}

#[derive(Debug, Clone, Serialize)]
pub struct EmbedProgressEvent {
    pub email_id: i64,
    pub done: u32,
    pub total: u32,
    pub error: Option<String>,
}

/// Mirrors `triage_all_untriaged`'s pattern exactly: finds emails with no embedding for
/// the current `search::MODEL_VERSION`, embeds each in turn, streaming progress via
/// `embed-progress`. Manual fallback; sync triggers the same work automatically (ADR 0005).
#[tauri::command]
pub async fn embed_pending(app: AppHandle, account_id: Option<i64>) -> Result<u32, String> {
    embed_pending_inner(&app, account_id).await
}

/// Body of `embed_pending`, reachable from a spawned task (re-acquires state from the
/// `AppHandle` because `State<'_, _>` is not `'static`).
async fn embed_pending_inner(app: &AppHandle, account_id: Option<i64>) -> Result<u32, String> {
    let state = app
        .try_state::<AppState>()
        .ok_or("app state not initialised")?;
    let email_ids: Vec<i64> = {
        let conn = state.db.lock().map_err(|e| e.to_string())?;
        let mut stmt = conn
            .prepare(
                "SELECT e.id FROM emails e
                 LEFT JOIN email_embeddings ee ON ee.email_id = e.id
                 WHERE (?1 IS NULL OR e.account_id = ?1)
                   AND (ee.email_id IS NULL OR ee.model_version <> ?2)
                 ORDER BY e.received_at DESC",
            )
            .map_err(|e| e.to_string())?;
        let rows = stmt
            .query_map(params![account_id, search::MODEL_VERSION], |row| row.get(0))
            .map_err(|e| e.to_string())?
            .collect::<Result<Vec<i64>, _>>()
            .map_err(|e| e.to_string())?;
        rows
    };

    let total = email_ids.len() as u32;
    for (i, email_id) in email_ids.into_iter().enumerate() {
        let outcome = embed_one(&state, email_id).await;
        let event = EmbedProgressEvent {
            email_id,
            done: i as u32 + 1,
            total,
            error: outcome.err(),
        };
        let _ = app.emit("embed-progress", event);
    }
    Ok(total)
}

// --- Hybrid search (ADR 0001-0007) -----------------------------------------

#[derive(Debug, Serialize)]
pub struct SearchResultDto {
    pub email_id: i64,
    pub account_id: i64,
    pub gmail_thread_id: String,
    /// Messages in this result's conversation (ADR 0007).
    pub thread_count: u32,
    pub sender: String,
    pub subject: String,
    /// Plain text. Keyword hits: FTS5 snippet with matched terms wrapped in U+E000/U+E001;
    /// semantic-only hits: first 160 chars of the body (ADR 0006).
    pub snippet: String,
    pub received_at: String,
    /// Fused RRF score (ADR 0003).
    pub score: f32,
    /// Which sources matched: "keyword" and/or "semantic".
    pub matched: Vec<String>,
}

/// One search path: FTS5 keyword candidates always; embedding candidates when the model
/// is ready; merged with Reciprocal Rank Fusion (ADR 0003). Scope follows the current
/// view (ADR 0004). Results are individual messages (ADR 0007).
#[tauri::command]
pub async fn search(
    state: State<'_, AppState>,
    query: String,
    account_id: Option<i64>,
    label_id: Option<String>,
    danger_only: bool,
    limit: Option<u32>,
) -> Result<Vec<SearchResultDto>, String> {
    let Some(match_expr) = search::keyword::sanitize_query(&query) else {
        return Ok(Vec::new());
    };
    let limit = limit.unwrap_or(search::RESULT_CAP).min(search::RESULT_CAP) as usize;

    // Semantic side only when the worker is up and the model has finished loading;
    // otherwise this is plain keyword ranking (no separate mode).
    let embed_handle = {
        let slot = state.embed_llm.lock().map_err(|e| e.to_string())?;
        let ready = matches!(
            *state.embed_model_status.lock().map_err(|e| e.to_string())?,
            ModelStatus::Ready { .. }
        );
        if ready {
            slot.clone()
        } else {
            None
        }
    };
    let query_vec = match embed_handle {
        Some(handle) => handle.embed(search::prefix::query_text(&query)).await.ok(),
        None => None,
    };

    let conn = state.db.lock().map_err(|e| e.to_string())?;
    let keyword_hits = search::keyword::keyword_search(
        &conn,
        &match_expr,
        account_id,
        label_id.as_deref(),
        danger_only,
        search::CANDIDATES_PER_SOURCE,
    )?;
    let semantic_hits: Vec<(i64, f32)> = match query_vec {
        Some(vec) => {
            let candidates = search::load_candidates(&conn, account_id, label_id.as_deref(), danger_only)?;
            search::rank_semantic(&candidates, &vec, search::CANDIDATES_PER_SOURCE)
        }
        None => Vec::new(),
    };

    // Positions of each source in the fusion input; `FusedHit::sources` reports these.
    const KEYWORD_SOURCE: usize = 0;
    const SEMANTIC_SOURCE: usize = 1;
    let mut lists: [Vec<i64>; 2] = [Vec::new(), Vec::new()];
    lists[KEYWORD_SOURCE] = keyword_hits.iter().map(|h| h.0).collect();
    lists[SEMANTIC_SOURCE] = semantic_hits.iter().map(|h| h.0).collect();
    let mut fused = search::fusion::rrf(&lists, search::RRF_K);
    fused.truncate(limit);

    let snippets: std::collections::HashMap<i64, String> =
        keyword_hits.into_iter().map(|(id, _, snippet)| (id, snippet)).collect();

    let mut stmt = conn
        .prepare(
            "SELECT e.account_id, e.gmail_thread_id, e.sender, e.subject, e.body_text, e.received_at,
                    (SELECT COUNT(*) FROM emails t WHERE t.account_id = e.account_id AND t.gmail_thread_id = e.gmail_thread_id)
             FROM emails e WHERE e.id = ?1",
        )
        .map_err(|e| e.to_string())?;
    let mut results = Vec::with_capacity(fused.len());
    for hit in fused {
        let row: Option<(i64, String, String, String, String, String, i64)> = stmt
            .query_row(params![hit.id], |row| {
                Ok((
                    row.get(0)?,
                    row.get(1)?,
                    row.get(2)?,
                    row.get::<_, Option<String>>(3)?.unwrap_or_default(),
                    row.get::<_, Option<String>>(4)?.unwrap_or_default(),
                    row.get(5)?,
                    row.get(6)?,
                ))
            })
            .ok();
        let Some((account_id, gmail_thread_id, sender, subject, body_text, received_at, thread_count)) = row else {
            continue;
        };
        let snippet = match snippets.get(&hit.id) {
            Some(s) => s.clone(),
            None => body_text.chars().take(160).collect(),
        };
        let matched = hit
            .sources
            .iter()
            .filter_map(|s| match *s {
                KEYWORD_SOURCE => Some("keyword".to_string()),
                SEMANTIC_SOURCE => Some("semantic".to_string()),
                _ => None,
            })
            .collect();
        results.push(SearchResultDto {
            email_id: hit.id,
            account_id,
            gmail_thread_id,
            thread_count: thread_count as u32,
            sender,
            subject,
            snippet,
            received_at,
            score: hit.score,
            matched,
        });
    }
    Ok(results)
}

